// Convert src/generated/schemas.json (written by `uv run --frozen python scripts/gen_ts_types.py`
// from packages/contracts) into src/generated/contracts.ts with json-schema-to-typescript.
//
//   pnpm gen:types           write contracts.ts
//   pnpm gen:types --check   exit 1 if contracts.ts is stale
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const generatedDir = path.resolve(here, "..", "src", "generated");
const schemaPath = path.join(generatedDir, "schemas.json");
const outPath = path.join(generatedDir, "contracts.ts");
const check = process.argv.includes("--check");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const banner = [
  "/* eslint-disable */",
  "// GENERATED by apps/dashboard/scripts/gen-contracts.mjs (json-schema-to-typescript) from",
  "// src/generated/schemas.json, which scripts/gen_ts_types.py exports from packages/contracts.",
  "// Do not edit by hand: run `uv run --frozen python scripts/gen_ts_types.py && pnpm gen:types`.",
  `// Contract schema_version: ${schema["x-lat-schema-version"]}; risk policy schema: ${schema["x-lat-policy-schema"]}.`,
  "",
  "/** Canonical decimal string (Python Decimal serialized with format(value, 'f')). Never parse with parseFloat for accounting. */",
  "export type DecimalString = string;",
  "/** ISO-8601 UTC timestamp string ending in 'Z'. */",
  "export type UtcTimestamp = string;",
].join("\n");

let ts = await compile(schema, schema.title ?? "LatContracts", {
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  unknownAny: true,
  format: true,
  style: { printWidth: 110, singleQuote: false, trailingComma: "all" },
});
ts = ts.endsWith("\n") ? ts : ts + "\n";

if (check) {
  let current = "";
  try {
    current = await readFile(outPath, "utf8");
  } catch {
    current = "";
  }
  if (current !== ts) {
    console.error("stale: src/generated/contracts.ts -- run `pnpm gen:types`");
    process.exit(1);
  }
  console.log("src/generated/contracts.ts is up to date");
} else {
  await writeFile(outPath, ts, "utf8");
  const count = (ts.match(/^export (interface|type) /gm) ?? []).length;
  console.log(`wrote src/generated/contracts.ts (${count} exported types)`);
}
