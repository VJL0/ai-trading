import { expect, test } from "@playwright/test";
const MOCK = process.env.LAT_E2E_MOCK_URL ?? "http://127.0.0.1:18765";
test.beforeEach(async ({ page }) => { await page.request.post(`${MOCK}/__mock/reset`); });
test("GPU unavailable preserves inspection, replay, and read-only streaming", async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, "gpu", { value: undefined }));
  await page.goto("/");
  await expect(page.getByRole("heading", {name:"Market Mycelium"})).toBeVisible();
  await expect(page.getByRole("heading", {name:"Memory remains available."})).toBeVisible();
  await expect(page.locator(".myc-event").first()).toBeVisible();
  const count = await page.locator(".myc-event").count();
  await page.getByRole("button", {name:"Explore memory",exact:true}).click();
  await expect(page.getByLabel("Replay time")).toBeVisible();
  expect(await page.locator(".myc-event").count()).toBeLessThan(count);
  await page.getByLabel("Replay time").fill(await page.getByLabel("Replay time").getAttribute("max") ?? "0");
  await expect(page.locator(".myc-event")).toHaveCount(count);
  await page.locator(".myc-event").filter({hasText:"AAPL · BUY · REJECTED"}).click();
  await expect(page.locator(".myc-detail")).toContainText("uncalibrated");
  await expect(page.locator(".myc-detail pre")).toContainText('"confidence": "0.54"');
  await page.getByRole("button", {name:"Return to live",exact:true}).click();
  await page.request.post(`${MOCK}/__mock/play`);
  await expect(page.getByTestId("lifecycle-lat-sim-01jbdashfixture00000filled1")).toHaveAttribute("data-state", "FILLED", {timeout:20000});
  await page.getByRole("button", {name:"Retry WebGPU"}).click();
  await expect(page.getByRole("heading", {name:"Memory remains available."})).toBeVisible();
  expect(await page.locator(".myc-surface canvas").count()).toBe(1);
});
test("replay freezes its history while live events arrive and reduced motion is respected", async ({page}) => {
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.goto("/");
  await expect(page.locator(".myc-event").first()).toBeVisible();
  await expect(page.getByRole("button", {name:"Motion paused",exact:true})).toBeDisabled();
  await page.getByRole("button", {name:"Explore memory",exact:true}).click();
  const max = await page.getByLabel("Replay time").getAttribute("max");
  await page.request.post(`${MOCK}/__mock/play`);
  await expect(page.getByTestId("lifecycle-lat-sim-01jbdashfixture00000filled1")).toHaveAttribute("data-state", "FILLED", {timeout:20000});
  expect(await page.getByLabel("Replay time").getAttribute("max")).toBe(max);
  await page.getByRole("button", {name:"Return to live",exact:true}).click();
  await expect(page.locator(".myc-event").filter({hasText:"FILLED"}).first()).toBeVisible();
});
