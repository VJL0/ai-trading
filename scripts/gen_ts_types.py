"""Export the Pydantic contracts to JSON Schema for the dashboard's generated TypeScript types.

Usage (from the project root)::

    uv run --frozen python scripts/gen_ts_types.py           # write the generated files
    uv run --frozen python scripts/gen_ts_types.py --check   # exit 1 if they are out of date

Writes:

* ``apps/dashboard/src/generated/schemas.json`` -- one JSON Schema bundle whose ``$defs`` hold every
  model exported by ``packages.contracts`` (plus ``RiskPolicy``) and every enum they reference.
  ``pnpm gen:types`` (apps/dashboard/scripts/gen-contracts.mjs) converts it to ``contracts.ts``
  with json-schema-to-typescript.
* ``apps/dashboard/src/generated/enums.ts`` -- runtime ``as const`` arrays of every enum's values and
  the contract constants the UI needs at runtime (``SCHEMA_VERSION``, ``TERMINAL_ORDER_STATES``).

Schemas are produced in Pydantic *serialization* mode because the dashboard consumes the JSON the
API emits (``model_dump(mode="json")``): every ``Decimal`` (the ``Dec`` type) is a canonical decimal
*string* (``x-lat-kind: decimal``, TypeScript ``DecimalString``) and every timestamp is an ISO-8601
UTC string ending in ``Z`` (``x-lat-kind: utc-datetime``, TypeScript ``UtcTimestamp``). Because
``model_dump`` always emits fields that have defaults, every property is marked ``required``;
nullability is preserved through ``anyOf [..., null]``.
"""

from __future__ import annotations

import argparse
import inspect
import json
import sys
import typing
from datetime import datetime
from decimal import Decimal
from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import JsonSchemaMode, models_json_schema

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import packages.contracts as contracts  # noqa: E402
from packages.contracts import enums as contract_enums  # noqa: E402
from packages.contracts.models import SCHEMA_VERSION  # noqa: E402
from packages.contracts.policy import POLICY_SCHEMA, RiskPolicy  # noqa: E402

OUT_DIR = PROJECT_ROOT / "apps" / "dashboard" / "src" / "generated"
SCHEMAS_PATH = OUT_DIR / "schemas.json"
ENUMS_PATH = OUT_DIR / "enums.ts"

BUNDLE_TITLE = "LatContracts"
DECIMAL_TS_TYPE = "DecimalString"
DATETIME_TS_TYPE = "UtcTimestamp"

_GENERATED_NOTE = "GENERATED by scripts/gen_ts_types.py from packages/contracts -- do not edit by hand."


# ------------------------------------------------------------------------------------------------
# Discovery
# ------------------------------------------------------------------------------------------------


def contract_models() -> list[type[BaseModel]]:
    """Every Pydantic model exported by ``packages.contracts`` (sorted by name), plus RiskPolicy."""
    found: dict[str, type[BaseModel]] = {}
    for name in sorted(contracts.__all__):
        obj = getattr(contracts, name)
        if inspect.isclass(obj) and issubclass(obj, BaseModel):
            found[obj.__name__] = obj
    found.setdefault(RiskPolicy.__name__, RiskPolicy)
    return [found[k] for k in sorted(found)]


def contract_enums_list() -> list[type[Enum]]:
    out: list[type[Enum]] = []
    for name in sorted(dir(contract_enums)):
        obj = getattr(contract_enums, name)
        if inspect.isclass(obj) and issubclass(obj, Enum) and obj.__module__ == contract_enums.__name__:
            out.append(obj)
    return out


# ------------------------------------------------------------------------------------------------
# Field kind detection (Decimal / datetime) from the Python annotations
# ------------------------------------------------------------------------------------------------


def _leaf_kinds(annotation: Any) -> set[str]:
    """Return {'decimal', 'datetime'} members found anywhere in an annotation (through Optional,
    Annotated, unions and containers)."""
    kinds: set[str] = set()
    if annotation is Decimal:
        kinds.add("decimal")
        return kinds
    if annotation is datetime:
        kinds.add("datetime")
        return kinds
    origin = typing.get_origin(annotation)
    if origin is typing.Annotated:
        args = typing.get_args(annotation)
        return _leaf_kinds(args[0]) if args else kinds
    if origin is None:
        return kinds
    for arg in typing.get_args(annotation):
        if arg is Ellipsis or arg is type(None):
            continue
        kinds |= _leaf_kinds(arg)
    return kinds


def _field_kinds(model: type[BaseModel]) -> dict[str, str]:
    out: dict[str, str] = {}
    for name, info in model.model_fields.items():
        kinds = _leaf_kinds(info.annotation)
        if len(kinds) > 1:
            raise SystemExit(f"{model.__name__}.{name}: mixed decimal/datetime annotation is unsupported")
        if kinds:
            out[name] = kinds.pop()
    return out


# ------------------------------------------------------------------------------------------------
# Schema post-processing
# ------------------------------------------------------------------------------------------------


def _normalize(node: Any) -> Any:
    """Prepare nested (property-level) schemas for json-schema-to-typescript.

    * ``title`` is removed so the converter does not emit one alias per titled property
      (``type Open = string``). Titles on ``$defs`` are re-added by the caller.
    * A ``$ref`` with siblings (``default``/``description``) would make the converter emit a
      duplicate named type (``OrderState1``), so the siblings are dropped (defaults and field docs
      remain in the Python contracts, the source of truth).
    """
    if isinstance(node, dict):
        mapping = typing.cast(dict[str, Any], node)
        if "$ref" in mapping:
            return {"$ref": mapping["$ref"]}
        return {k: _normalize(v) for k, v in mapping.items() if k != "title"}
    if isinstance(node, list):
        return [_normalize(v) for v in typing.cast(list[Any], node)]
    return node


def _mark_string_kind(prop: dict[str, Any], kind: str, where: str) -> None:
    ts_type = DECIMAL_TS_TYPE if kind == "decimal" else DATETIME_TS_TYPE
    lat_kind = "decimal" if kind == "decimal" else "utc-datetime"
    targets: list[dict[str, Any]] = []

    def visit(node: dict[str, Any]) -> None:
        if node.get("type") == "string":
            targets.append(node)
        for key in ("anyOf", "oneOf", "allOf"):
            for sub in node.get(key, []):
                visit(sub)
        items = node.get("items")
        if isinstance(items, dict):
            visit(typing.cast(dict[str, Any], items))
        prefix = node.get("prefixItems")
        if isinstance(prefix, list):
            for sub in typing.cast(list[dict[str, Any]], prefix):
                visit(sub)

    visit(prop)
    if not targets:
        raise SystemExit(f"{where}: expected a string schema for a {kind} field, got {json.dumps(prop)}")
    for node in targets:
        node["tsType"] = ts_type
        node["x-lat-kind"] = lat_kind
        if kind == "datetime":
            node["format"] = "date-time"


def build_bundle(mode: JsonSchemaMode = "serialization") -> dict[str, Any]:
    models = contract_models()
    _, top = models_json_schema([(m, mode) for m in models], ref_template="#/$defs/{model}")
    defs: dict[str, Any] = dict(top.get("$defs", {}))

    # Every enum in packages.contracts.enums, even ones no model references yet.
    for enum_cls in contract_enums_list():
        if enum_cls.__name__ not in defs:
            defs[enum_cls.__name__] = {
                "enum": [member.value for member in enum_cls],
                "title": enum_cls.__name__,
                "type": "string",
            }

    out_defs: dict[str, Any] = {}
    by_name = {m.__name__: m for m in models}
    for def_name in sorted(defs):
        schema = defs[def_name]
        title = schema.get("title", def_name)
        cleaned = _normalize(schema)
        cleaned["title"] = title
        model = by_name.get(def_name)
        if model is not None:
            props: dict[str, Any] = cleaned.get("properties", {})
            for field_name, kind in _field_kinds(model).items():
                alias = model.model_fields[field_name].serialization_alias or field_name
                if alias not in props:
                    raise SystemExit(f"{def_name}.{alias}: field missing from generated schema")
                _mark_string_kind(props[alias], kind, f"{def_name}.{alias}")
            # model_dump(mode="json") always emits every field (defaults included).
            cleaned["required"] = list(props.keys())
            # Only the model's *own* docstring: inspect.getdoc() would inherit pydantic.BaseModel's
            # generic docstring for contracts that have none.
            own = model.__dict__.get("__doc__")
            doc = inspect.cleandoc(own) if isinstance(own, str) and own.strip() else None
            if doc and not cleaned.get("description"):
                cleaned["description"] = doc
        out_defs[def_name] = cleaned

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": _GENERATED_NOTE,
        "title": BUNDLE_TITLE,
        "description": (
            "All packages.contracts models (serialization mode). Decimal fields are canonical decimal "
            "strings; timestamps are ISO-8601 UTC strings ending in Z."
        ),
        "x-lat-schema-version": SCHEMA_VERSION,
        "x-lat-policy-schema": POLICY_SCHEMA,
        "type": "object",
        "additionalProperties": False,
        "properties": {name: {"$ref": f"#/$defs/{name}"} for name in sorted(by_name)},
        "$defs": out_defs,
    }


# ------------------------------------------------------------------------------------------------
# enums.ts (runtime values)
# ------------------------------------------------------------------------------------------------


def _ts_string(value: str) -> str:
    return json.dumps(value)


def build_enums_ts() -> str:
    lines = [
        f"// {_GENERATED_NOTE}",
        "// Runtime value lists for the contract enums (types live in ./contracts.ts).",
        "",
        f"export const SCHEMA_VERSION = {_ts_string(SCHEMA_VERSION)} as const;",
        f"export const POLICY_SCHEMA = {_ts_string(POLICY_SCHEMA)} as const;",
        "",
    ]
    for enum_cls in contract_enums_list():
        values = ", ".join(_ts_string(str(m.value)) for m in enum_cls)
        const_name = "".join("_" + c if c.isupper() else c.upper() for c in enum_cls.__name__).lstrip("_")
        lines.append(f"export const {const_name}_VALUES = [{values}] as const;")
    terminal = sorted(str(s.value) for s in contract_enums.TERMINAL_ORDER_STATES)
    lines += [
        "",
        "/** Order states after which no further broker transition is expected (packages.contracts.enums). */",
        f"export const TERMINAL_ORDER_STATES = [{', '.join(_ts_string(s) for s in terminal)}] as const;",
        "",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------------------------------
# CLI
# ------------------------------------------------------------------------------------------------


def render() -> dict[Path, str]:
    bundle = build_bundle()
    return {
        SCHEMAS_PATH: json.dumps(bundle, indent=2, sort_keys=False, ensure_ascii=False) + "\n",
        ENUMS_PATH: build_enums_ts(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)
    outputs = render()
    if args.check:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(PROJECT_ROOT)}")
        if stale:
            print("run: uv run --frozen python scripts/gen_ts_types.py && (cd apps/dashboard && pnpm gen:types)")
            return 1
        print("generated contract schemas are up to date")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(PROJECT_ROOT)}")
    n_models = len(contract_models())
    n_enums = len(contract_enums_list())
    print(f"{n_models} models, {n_enums} enums; next: (cd apps/dashboard && pnpm gen:types)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
